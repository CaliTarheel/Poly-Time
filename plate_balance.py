"""Instantaneous Stokes torque balance for whole plates.

The Reynolds number of the lithosphere is ~1e-20. Velocity is not integrated
from an acceleration; it is whatever makes the forces sum to zero at this
instant, and it changes discontinuously when the forces do. So there is no
inertia here, no velocity relaxation, no carried omega, no speed cap and no
by-fiat removal of net rotation. omega is solved from scratch every step and a
warm start changes only the iteration count, never the answer. Do not
reintroduce a lag: the measured spectral radius of explicitly coupling these
boundaries plate-by-plate is 26 (four plates) to 499, so a lagged coupling
diverges and a relaxation time only hides the divergence behind a filter.

Forces are SUMMED over the boundary where they act. A plate with 6,000 km of
trench is pulled by 6,000 km of slab. The retired raster law divided each
driver by the number of contributing edges, which made a plate's drive depend
on how finely its boundary happened to be meshed and silently cancelled
opposing segments before any constitutive law saw them.

STRUCTURE. The unknown is x_p = omega_p * R / v0, so that a relative velocity
reads directly in cm/yr and the conditioning does not depend on the radius.
The functional is convex:

    Phi(x) = 1/2 x.K x - T.x + sum_e D_e(x)

K collects the genuinely viscous resistances (asthenosphere drag under every
cell, slab Stokes drag and slab anchoring at trenches, hinge bending), T the
drivers (slab weight, ridge push, and the rigid share of the collision GPE),
and D_e the rate-independent plastic elements (megathrust, strike-slip,
distributed compression, and the suture weld). Plastic terms are regularised
and the regulariser is continued down 100/10/1/0.1 km/Myr. This is a finite
smoothing width, not evidence of convergence to the plastic limit. Relative
motion below that scale can be regularisation creep and needs a refinement
check. K is symmetric positive definite and the potentials are convex.

Constitutive version 1 uses passive one-sided compression and megathrust
laws: no normal traction is generated by opening. Version 0 preserves the
historical smooth-tail law for existing checkpoints; that law can supply
negative resisting work and must not be interpreted as passive friction.
Actual resisting work x.grad(D) is reported separately from the potential D.

WHAT IS NOT MODELLED, stated so nothing here is mistaken for a measurement:
slab dip (fixed, see slab_memory.SUBDUCTION_DIP_DEG), slab tip depth, along-slab
age structure, lower-mantle slab support, trench suction as a separate term,
sediment supply at the interface, and any intraplate stress field. Every
coefficient below carries a literature bracket in its comment; none of them is
derivable from this model's own state.
"""
